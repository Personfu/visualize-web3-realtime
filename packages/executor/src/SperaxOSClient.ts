import type { AgentIdentity, AgentTask, AgentEvent } from './types.js';
import type { AgentSpawnConfig } from './types.js';
import WebSocket from 'ws';

/**
 * Client for the SperaxOS agent API.
 *
 * When no API key is configured, operates in mock mode — generating synthetic
 * agent events without connecting to the real API.
 */
export class SperaxOSClient {
  private mockMode: boolean;

  constructor(
    private readonly baseUrl: string,
    private readonly apiKey: string,
  ) {
    try {
      const url = new URL(baseUrl);
      const loopback = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
      if (url.username || url.password || url.search || url.hash ||
          (url.protocol !== 'https:' && !(url.protocol === 'http:' && loopback))) throw new Error();
      this.baseUrl = url.href.replace(/\/$/, '');
      if (apiKey.length > 4096 || /[\x00-\x20\x7f]/.test(apiKey)) throw new Error();
    } catch {
      throw new Error('Invalid upstream connection configuration');
    }
    this.mockMode = !apiKey;
    if (this.mockMode) {
      console.log('[SperaxOSClient] No API key — operating in mock mode');
    }
  }

  async spawnAgent(config: AgentSpawnConfig): Promise<AgentIdentity> {
    if (this.mockMode) {
      return {
        agentId: `mock_agent_${Date.now()}`,
        name: config.name ?? `Mock${config.role}`,
        role: config.role,
        createdAt: Date.now(),
      };
    }

    const res = await fetch(`${this.baseUrl}/agents/v1/spawn`, {
      method: 'POST',
      redirect: 'error',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify(config),
    });

    if (!res.ok) throw new Error(`SperaxOS spawn failed: ${res.status}`);
    return res.json() as Promise<AgentIdentity>;
  }

  async executeTask(agentId: string, task: AgentTask): Promise<void> {
    if (this.mockMode) return;

    const res = await fetch(`${this.baseUrl}/agents/v1/agents/${encodeURIComponent(agentId)}/tasks`, {
      method: 'POST',
      redirect: 'error',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify(task),
    });

    if (!res.ok) throw new Error(`SperaxOS executeTask failed: ${res.status}`);
  }

  async getAgentStatus(agentId: string): Promise<AgentIdentity> {
    if (this.mockMode) {
      return {
        agentId,
        name: agentId,
        role: 'unknown',
        createdAt: Date.now(),
      };
    }

    const res = await fetch(`${this.baseUrl}/agents/v1/agents/${encodeURIComponent(agentId)}`, {
      redirect: 'error',
      headers: { Authorization: `Bearer ${this.apiKey}` },
    });

    if (!res.ok) throw new Error(`SperaxOS getAgentStatus failed: ${res.status}`);
    return res.json() as Promise<AgentIdentity>;
  }

  subscribeEvents(agentId: string, callback: (event: AgentEvent) => void): () => void {
    if (this.mockMode) {
      // No real WebSocket in mock mode — events are generated by AgentManager
      return () => {};
    }

    const stream = new URL(`${this.baseUrl.replace(/^http/, 'ws')}/agents/v1/stream`);
    stream.searchParams.set('agentId', agentId);
    const ws = new WebSocket(stream, {
      headers: { Authorization: `Bearer ${this.apiKey}` },
      followRedirects: false,
      maxPayload: 1024 * 1024,
    });

    ws.on('message', (data) => {
      try {
        const event = JSON.parse(data.toString()) as AgentEvent;
        callback(event);
      } catch {
        // ignore
      }
    });
    ws.on('error', () => {});

    return () => ws.close();
  }

  async healthCheck(): Promise<boolean> {
    if (this.mockMode) return true;
    try {
      const res = await fetch(`${this.baseUrl}/health`, {
        redirect: 'error',
        headers: { Authorization: `Bearer ${this.apiKey}` },
        signal: AbortSignal.timeout(5000),
      });
      return res.ok;
    } catch {
      return false;
    }
  }
}
